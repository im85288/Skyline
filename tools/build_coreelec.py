"""CoreELEC's settings window in Skyline's colours.

    python3 tools/build_coreelec.py

The settings add-on (service.coreelec.settings, opened from Settings'
CoreELEC tile) draws its own window. CoreELEC 21 hard-codes its red
(FFC40300) for the background, focus bars and separators, so it looked
like another product inside Skyline. Kodi looks for an add-on's window in
the current skin before the add-on's own folder, so Skyline ships the
window itself: CoreELEC 22's (tools/source/coreelec), which has the same
controls as 21's and takes its colours from the skin's names
(primary_background, button_focus, red, white), here Skyline's.

A window found in the skin looks its images up in the skin, not the
add-on, so each of the add-on's images is pointed at the add-on's folder.
The first-run wizard is left as CoreELEC's: its controls differ by version.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'tools', 'source', 'coreelec')
MEDIA = 'special://xbmc/addons/service.coreelec.settings/resources/skins/Default/media/'
WINDOWS = ('service-CoreELEC-Settings-mainWindow.xml', 'service-CoreELEC-Settings-getPasskey.xml')


def skyline(text):
    # The add-on's own images, by path (a bare name would be looked up in Skyline's media).
    text = re.sub(r'>([A-Za-z0-9_.-]+\.(?:png|jpg))<', lambda m: '>%s%s<' % (MEDIA, m.group(1)), text)
    # The page behind: Skyline's background, which the colour themes change.
    text = text.replace('<texture colordiffuse="primary_background">', '<texture colordiffuse="SkylineBackground">')
    return '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by tools/build_coreelec.py from CoreELEC 22\'s ' \
           'window: edit that, not this. -->\n' + text.split('\n', 1)[1]


def main():
    for name in WINDOWS:
        with open(os.path.join(SOURCE, name), encoding='utf-8') as handle:
            text = skyline(handle.read())
        with open(os.path.join(ROOT, 'xml', name), 'w', encoding='utf-8') as handle:
            handle.write(text)
    print('Wrote %s' % ', '.join(WINDOWS))


if __name__ == '__main__':
    main()
